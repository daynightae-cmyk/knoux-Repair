export function pickName(t: { EnglishName: string; ArabicName: string }, lang: Lang): string {
  if (lang === 'ar') return t.ArabicName || t.EnglishName;
  return t.EnglishName;
}

export function formatUptime(seconds: number, lang: Lang): string {
  const d = Math.floor(seconds / 86400);
  const h = Math.floor((seconds % 86400) / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  if (lang === 'ar') return `${d}ي ${h}س ${m}د`;
  return `${d}d ${h}h ${m}m`;
}